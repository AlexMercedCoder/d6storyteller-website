// Copies the D6 Storyteller book facts (title, books-site page, Amazon link) from the
// entity layer, alexmercedcom/entity/books.json, into src/data/d6-books.json.
// Run locally after the entity layer changes: `npm run sync:books`.
// The build reads the committed JSON, so Netlify does not need the entity repo.
import { readFileSync, writeFileSync } from 'node:fs';

const source = new URL('../../alexmercedcom/entity/books.json', import.meta.url);
const { books } = JSON.parse(readFileSync(source, 'utf8'));
const d6 = books
  .filter((b) => b.slug.startsWith('d6-storyteller-'))
  .map(({ slug, title, canonicalPage, url }) => ({ slug, title, canonicalPage, amazon: url }));
writeFileSync(
  new URL('../src/data/d6-books.json', import.meta.url),
  JSON.stringify({ '//': 'Generated by scripts/sync-d6-books.mjs from alexmercedcom/entity/books.json. Do not edit by hand.', books: d6 }, null, 2) + '\n',
);
console.log(`wrote ${d6.length} D6 books`);
